/**
 * gen-registry.mjs — derive the family/theme registry from the SCSS sources.
 *
 * Single source of truth = the files under src/scss:
 *   - families:   src/scss/families/<name>.scss   (excluding _partials)
 *   - themes:     src/scss/themes/<family>/<name>.scss
 *   - parameters: declared in the family's SCSS, read back out of its
 *                 compiled CSS (see src/scss/_params.scss)
 *
 * Each family owns its own set of parameters. Reading them from the family
 * rather than restating them in TypeScript is what keeps that true: rename a
 * variable in the SCSS and the configurator follows it.
 *
 * To add a family:   drop src/scss/families/<name>.scss + a themes/<name>/ folder.
 * To add a theme:    drop src/scss/themes/<family>/<name>.scss.
 * Then run `pnpm run build:css` (this script runs last, after sass).
 *
 * Output: src/lib/generated/registry.ts (git-ignored, regenerated on build).
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const familiesDir = join(root, 'src/scss/families');
const themesDir = join(root, 'src/scss/themes');
const builtDir = join(root, 'static/families');
const outFile = join(root, 'src/lib/generated/registry.ts');

const NL = String.fromCharCode(10);

/** List `*.scss` basenames in a dir, excluding `_partials`. */
function scssNames(dir) {
	if (!existsSync(dir)) return [];
	return readdirSync(dir)
		.filter((f) => f.endsWith('.scss') && !f.startsWith('_'))
		.map((f) => f.replace(/\.scss$/, ''))
		.sort();
}

/** Parse a theme scss file into { scheme, vars }. */
function parseTheme(file) {
	const src = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
	const vars = {};
	for (const m of src.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) {
		vars[m[1].trim()] = m[2].trim();
	}
	const scheme = src.match(/color-scheme\s*:\s*([^;]+);/);
	return { scheme: scheme ? scheme[1].trim() : 'light', vars };
}

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

/** A family's parameter declaration, emitted into its compiled CSS. */
function parseParams(family) {
	const file = join(builtDir, `${family}.css`);
	if (!existsSync(file)) return [];
	const m = readFileSync(file, 'utf8').match(/uu-params (\[[\s\S]*?\]) \*\//);
	if (!m) return [];
	try {
		return JSON.parse(m[1]);
	} catch {
		console.warn(`registry: ${family} has an unreadable uu-params comment`);
		return [];
	}
}

/**
 * The family's own header comment, split into what the Families page shows:
 * the parenthetical after the name, the prose, and the deliberate departures
 * listed under "Changes made to fit our contract".
 */
function parseDoc(family) {
	const src = readFileSync(join(familiesDir, family, 'index.scss'), 'utf8');
	const empty = { title: cap(family), after: '', blurb: '', changes: [] };

	const header = src.match(/\/\*\s*=+([\s\S]*?)=+\s*\*\//);
	if (!header) return empty;

	const lines = header[1].split(NL).map((l) => l.replace(/^\s*/, '').trimEnd());
	const titleIndex = lines.findIndex((l) => l.startsWith('STYLE FAMILY'));
	if (titleIndex < 0) return empty;

	const after = (lines[titleIndex].match(/\(([^)]*)\)\s*$/) || [, ''])[1].trim();

	const prose = [];
	for (const line of lines.slice(titleIndex + 1)) {
		if (/^(Changes made|Build:)/.test(line)) break;
		prose.push(line);
	}

	const blurb = prose
		.join(NL)
		.split(new RegExp(`${NL}\\s*${NL}`))
		.map((p) => p.replace(new RegExp(`\\s*${NL}\\s*`, 'g'), ' ').trim())
		.filter(Boolean)
		.join(NL + NL);

	const section = header[1].match(/Changes made[^\n]*\n([\s\S]*?)\n\s*Build:/);
	const changes = section
		? section[1]
				.split(/(?:^|\n)\s*-\s+/)
				.map((item) => item.replace(/\s*\n\s*/g, ' ').trim())
				.filter(Boolean)
		: [];

	return { title: cap(family), after, blurb, changes };
}

/* A family is a directory with an index.scss (ADR 0008). */
const families = readdirSync(familiesDir)
	.filter((name) => existsSync(join(familiesDir, name, 'index.scss')))
	.sort();

const themesByFamily = {};
const paramsByFamily = {};
const familyDocs = {};
for (const family of families) {
	const dir = join(themesDir, family);
	themesByFamily[family] = scssNames(dir).map((name) => {
		const { scheme, vars } = parseTheme(join(dir, `${name}.scss`));
		return { name, label: cap(name), scheme, vars };
	});
	paramsByFamily[family] = parseParams(family);
	familyDocs[family] = parseDoc(family);
}

const j = (v) => JSON.stringify(v, null, '\t');

const body = [
	'// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.',
	'',
	'export interface ThemeData {',
	'\tname: string;',
	'\tlabel: string;',
	'\tscheme: string;',
	'\tvars: Record<string, string>;',
	'}',
	'',
	'/** A variable a family exposes. Declared in the family SCSS, not here. */',
	'export interface FamilyParam {',
	'\tname: string;',
	'\tlabel: string;',
	'\tgroup: string;',
	'\ttype: string;',
	'\tvalue: string;',
	'\tdescription?: string;',
	'\tmin?: number;',
	'\tmax?: number;',
	'\tstep?: number;',
	'\tunit?: string;',
	'\tunits?: string[];',
	'\t/** Colours only: surface | accent | ink. */',
	'\tkind?: string;',
	'\t/** Colours only: the variable holding the ink written on this one. */',
	'\ton?: string;',
	'}',
	'',
	'/** What the Families page shows about a family, read from its header. */',
	'export interface FamilyDoc {',
	'\ttitle: string;',
	'\tafter: string;',
	'\tblurb: string;',
	'\tchanges: string[];',
	'}',
	'',
	`export const families: string[] = ${JSON.stringify(families)};`,
	'',
	`export const themesByFamily: Record<string, ThemeData[]> = ${j(themesByFamily)};`,
	'',
	`export const paramsByFamily: Record<string, FamilyParam[]> = ${j(paramsByFamily)};`,
	'',
	`export const familyDocs: Record<string, FamilyDoc> = ${j(familyDocs)};`,
	''
].join(NL);

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);

const themes = Object.values(themesByFamily).reduce((n, t) => n + t.length, 0);
const params = Object.values(paramsByFamily).reduce((n, p) => n + p.length, 0);
console.log(
	`registry: ${families.length} families, ${themes} themes, ${params} parameters → ${outFile}`
);
