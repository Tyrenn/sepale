/**
 * gen-registry.mjs — derive the family/theme registry from the SCSS sources.
 *
 * Single source of truth = the files under src/scss:
 *   - families:  src/scss/families/<name>.scss   (excluding _partials)
 *   - themes:    src/scss/themes/<family>/<name>.scss
 *
 * To add a family:   drop src/scss/families/<name>.scss + a themes/<name>/ folder.
 * To add a theme:    drop src/scss/themes/<family>/<name>.scss.
 * Then run `npm run build:css` (this script runs as part of it).
 *
 * Output: src/lib/generated/registry.ts (git-ignored, regenerated on build).
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const familiesDir = join(root, 'src/scss/families');
const themesDir = join(root, 'src/scss/themes');
const outFile = join(root, 'src/lib/generated/registry.ts');

/** List `*.scss` basenames in a dir, excluding `_partials`. */
function scssNames(dir) {
	if (!existsSync(dir)) return [];
	return readdirSync(dir)
		.filter((f) => f.endsWith('.scss') && !f.startsWith('_'))
		.map((f) => f.replace(/\.scss$/, ''))
		.sort();
}

/** Parse a theme scss file into { scheme, vars }. */
function parseTheme(file) {
	const src = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
	const vars = {};
	for (const m of src.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) {
		vars[m[1].trim()] = m[2].trim();
	}
	const scheme = src.match(/color-scheme\s*:\s*([^;]+);/);
	return { scheme: scheme ? scheme[1].trim() : 'light', vars };
}

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const families = scssNames(familiesDir);

const themesByFamily = {};
for (const family of families) {
	const dir = join(themesDir, family);
	themesByFamily[family] = scssNames(dir).map((name) => {
		const { scheme, vars } = parseTheme(join(dir, `${name}.scss`));
		return { name, label: cap(name), scheme, vars };
	});
}

const banner = '// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.\n';
const body =
	banner +
	'\nexport interface ThemeData {\n' +
	'\tname: string;\n\tlabel: string;\n\tscheme: string;\n\tvars: Record<string, string>;\n}\n\n' +
	`export const families: string[] = ${JSON.stringify(families)};\n\n` +
	`export const themesByFamily: Record<string, ThemeData[]> = ${JSON.stringify(themesByFamily, null, '\t')};\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);

const total = Object.values(themesByFamily).reduce((n, t) => n + t.length, 0);
console.log(`registry: ${families.length} families, ${total} themes → ${outFile}`);
