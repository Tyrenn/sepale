import type { Draft } from './schema.js';

/**
 * The shipped themes, as drafts.
 *
 * A preset is a draft and not a stylesheet on purpose. A theme file is flat —
 * numbers, with three sentinels naming the effect modes that produced them —
 * and a flat file cannot give back everything: which edges a shadow was asked
 * for, whether an offset was a push or a sink. Keeping the draft as the source
 * means the generator opens a preset exactly as the person who made it left
 * it, and `scripts/build-themes.mjs` writes the CSS from the same schema a
 * download uses. One path, no second implementation.
 *
 * These four are what the families used to be. The rest of the nineteen are
 * colour variations of them and land with the remaining components.
 */

